def test_bm25_ranks_the_relevant_document_first():
    docs = [
        "delivery service level agreement metro non-metro business days",
        "warranty repair turnaround ten business days",
        "the quick brown fox jumps over the lazy dog",
    ]
    bm25 = BM25(docs)
    hits = bm25.search("delivery service level")
    assert hits[0][0] == 0


