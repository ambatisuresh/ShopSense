@pytest.mark.parametrize("filename", list(EXPECTED_FINDINGS))
def test_playbook_rag_end_to_end_per_contract(filename):
    state = _run_full_playbook_rag(filename)
    expected = EXPECTED_FINDINGS[filename]

    assert len(state["playbook_findings"]) == len(state["clauses"])
    by_id = {f["clause_id"]: f for f in state["playbook_findings"]}

    for clause_id, want in expected.items():
        got = by_id[clause_id]
        if want.get("status") == "skipped":
            assert got["status"] == "skipped"
            continue

        assert got["status"] == "found"
        assert got["position"]["clause_number"] == want["playbook_clause"]
        has_passages = bool(got["retrieved_passages"])
        assert has_passages == want["has_passages"], (
            f"{filename} clause {clause_id}: expected has_passages="
            f"{want['has_passages']}, got {has_passages}"
        )
        if want["has_passages"]:
            top = got["retrieved_passages"][0]
            assert top["doc"] == want["top_doc"]
            if "top_section" in want:
                assert top["section_id"] == want["top_section"]


