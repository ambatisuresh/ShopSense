@pytest.mark.parametrize("filename,expected", list(EXPECTED_CLAUSE_TYPES.items()))
def test_extraction_node_end_to_end_per_contract(filename, expected):
    state = seed_state(f"data/contracts/{filename}")
    result = extraction_node(state)

    assert result["contract_text"], "extraction must load and return the contract text"
    assert len(result["clauses"]) == len(expected)
    for clause in result["clauses"]:
        want = expected[clause["clause_id"]] or "unclassified"
        assert clause["clause_type"] == want, (
            f"{filename} clause {clause['clause_id']}: "
            f"expected {want!r}, got {clause['clause_type']!r}"
        )
        assert clause["text"], f"{filename} clause {clause['clause_id']} has empty text"


def test_extraction_node_output_stays_inside_its_write_scope():
    state = seed_state("data/contracts/vendor_payments_processor_agreement.md")
    result = extraction_node(state)
    allowed = AGENT_SCOPES["extraction"] | {"log"}
    assert set(result) <= allowed, f"extraction wrote outside its scope: {set(result) - allowed}"


def test_extraction_node_logs_one_line_per_clause_plus_a_summary_line():
    state = seed_state("data/contracts/vendor_returns_processing_agreement.md")
    result = extraction_node(state)
    assert len(result["log"]) == len(result["clauses"]) + 1


def test_extraction_node_reuses_contract_text_already_in_state():
    """If contract_text is already populated (e.g. a caller pre-loaded it, or
    a future MCP-backed node set it), extraction must not re-read the file —
    it should just parse what's already there."""
    real_text = (CONTRACTS_DIR / "vendor_payments_processor_agreement.md").read_text(
        encoding="utf-8"
    )
    tampered_text = real_text.replace(
        "**3.1 Refund Settlement Authority**", "**3.1 Renamed For This Test**"
    )
    state = seed_state("data/contracts/does_not_exist_on_disk.md", contract_text=tampered_text)
    result = extraction_node(state)
    titles = {c["clause_id"]: c["title"] for c in result["clauses"]}
    assert titles["3.1"] == "Renamed For This Test"


def test_extraction_node_fetches_via_mcp_when_contract_text_is_unset():
    """The real Step 10 integration point, exercised for real (not the
    hermetic wrapper above): when contract_text is NOT pre-set,
    extraction_node must fetch it through the MCP contract-repository
    server (mcp_server/contract_server.py) rather than reading local disk
    directly. Skips cleanly if mcp isn't installed wherever this runs."""
    pytest.importorskip("mcp", reason="mcp SDK not installed in this environment")
    from team.nodes.extraction import extraction_node as real_extraction_node

    state = seed_state("data/contracts/vendor_payments_processor_agreement.md")
    assert not state["contract_text"]  # sanity: this test only means something if unset

    result = asyncio.run(real_extraction_node(state))
    on_disk = (CONTRACTS_DIR / "vendor_payments_processor_agreement.md").read_text(encoding="utf-8")
    assert result["contract_text"] == on_disk
    assert len(result["clauses"]) == len(EXPECTED_CLAUSE_TYPES["vendor_payments_processor_agreement.md"])