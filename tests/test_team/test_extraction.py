def test_every_clause_type_is_used_by_at_least_one_contract_clause():
    """A taxonomy entry the corpus never exercises is dead weight — this
    catches a typo in CLAUSE_TYPES or CLAUSE_TYPE_KEYWORDS that would
    otherwise silently go untested."""
    used = {
        clause_type
        for contract in EXPECTED_CLAUSE_TYPES.values()
        for clause_type in contract.values()
        if clause_type is not None
    }
    assert used == set(CLAUSE_TYPES)


@pytest.mark.parametrize(
    "filename,clause_id,expected_type",
    [
        (fname, cid, ctype)
        for fname, clauses in EXPECTED_CLAUSE_TYPES.items()
        for cid, ctype in clauses.items()
    ],
)
def test_fallback_classifier_matches_expected_clause_type(filename, clause_id, expected_type):
    text = (CONTRACTS_DIR / filename).read_text(encoding="utf-8")
    clauses = {c["clause_id"]: c for c in split_into_clauses(text)}
    title = clauses[clause_id]["title"]
    assert classify_clause_type_fallback(title) == expected_type


