    """warranty-policy.md's '## N. Title' parent headers (e.g. '## 5.
    Replacement vs. Repair Decision Rule') have no direct body text of their
    own — their content lives entirely under their '### N.N' children. This
    is expected, not a parsing bug — see the empty-body exclusion in
    playbook_rag._policy_index()."""
    warranty_chunks = [c for c in load_policy_corpus() if c["doc"] == "warranty-policy.md"]
    empty = [c for c in warranty_chunks if not c["body"]]
    # sections 2, 3, 4, 5, 6, 7 are pure '## N. Title' parents whose content
    # lives entirely under their '### N.N' children; only section 1
    # (Introduction) has body text directly under its '##' heading.
    assert len(empty) == 6


