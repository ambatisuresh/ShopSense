CONTRACTS_DIR = REPO_ROOT / "data" / "contracts"


def _run_full_playbook_rag(contract_filename: str) -> dict:
    """Extraction, then playbook_rag_node driven one clause per call until
    every clause has a finding — the same loop scripts/run_playbook_rag.py
    uses. Returns the final state dict."""
    state = dict(seed_state(f"data/contracts/{contract_filename}"))
    state.update(extraction_node(state))
    for _ in range(len(state["clauses"])):
        update = playbook_rag_node(state)
        state["playbook_findings"] = state["playbook_findings"] + update.get("playbook_findings", [])
        state["log"] = state["log"] + update.get("log", [])
    return state


