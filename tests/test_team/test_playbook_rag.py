def test_playbook_rag_never_returns_an_empty_body_passage():
    """Regression test for the first bug this step caught: a header-only
    chunk (empty body) must never appear as a retrieved passage — there's
    nothing in it to ground a citation in."""
    for filename in EXPECTED_FINDINGS:
        state = _run_full_playbook_rag(filename)
        for finding in state["playbook_findings"]:
            for passage in finding.get("retrieved_passages", []):
                assert passage["snippet"], (
                    f"{filename} clause {finding['clause_id']} retrieved an "
                    f"empty-body passage: {passage['doc']} §{passage['section_id']}"
                )


def test_playbook_rag_never_retrieves_from_an_uncited_document():
    """Regression test for the second bug: when a playbook position cites
    specific docs, every retrieved passage must come from one of them —
    never a same-worded chunk from an unrelated policy file."""
    for filename in EXPECTED_FINDINGS:
        state = _run_full_playbook_rag(filename)
        for finding in state["playbook_findings"]:
            if finding["status"] != "found":
                continue
            cited = set(finding["position"]["cited_docs"])
            if not cited:
                assert finding["retrieved_passages"] == []
                continue
            for passage in finding["retrieved_passages"]:
                assert passage["doc"] in cited


def test_playbook_rag_node_fetches_playbook_via_mcp_when_cache_is_cold():
    """The real Step 10 integration point, exercised for real (not the
    hermetic module-cache priming above): with a genuinely cold
    _POSITIONS_CACHE, playbook_rag_node must fetch the negotiation playbook
    through the MCP server (mcp_server/contract_server.py's
    contracts://playbook/negotiation resource) and parse it into the same
    positions a local disk read would produce. Skips cleanly if mcp isn't
    installed wherever this runs."""
    pytest.importorskip("mcp", reason="mcp SDK not installed in this environment")
    from team.nodes.playbook_rag import playbook_rag_node as real_playbook_rag_node

    saved_cache = _playbook_rag_module._POSITIONS_CACHE
    _playbook_rag_module._POSITIONS_CACHE = None  # force a real MCP fetch
    try:
        state = dict(seed_state("data/contracts/vendor_payments_processor_agreement.md"))
        state["contract_text"] = (
            CONTRACTS_DIR / "vendor_payments_processor_agreement.md"
        ).read_text(encoding="utf-8")
        state.update(asyncio.run(_extraction_node_async(state)))

        # The first clause(s) may be "unclassified" (this contract's 1.1 and
        # 2.1 both are), in which case playbook_rag_node returns early
        # WITHOUT ever calling _positions() -- caught by an earlier version
        # of this test asserting fetched_positions after only one call and
        # getting None back. Loop until a real lookup actually happens.
        for _ in range(len(state["clauses"])):
            update = asyncio.run(real_playbook_rag_node(state))
            state["playbook_findings"] = state["playbook_findings"] + update.get("playbook_findings", [])
            if _playbook_rag_module._POSITIONS_CACHE is not None:
                break

        fetched_positions = _playbook_rag_module._POSITIONS_CACHE
        assert fetched_positions is not None, "no classified clause ever triggered a real lookup"
        assert fetched_positions == load_playbook_positions()
    finally:
        _playbook_rag_module._POSITIONS_CACHE = saved_cache  # restore for later tests